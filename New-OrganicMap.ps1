<#
    Builds "Broken Mesa" - a 1v1, 512 m, dry highland map.

    Where Serpent Crossing uses analytic plateaus, this thresholds a
    domain-warped noise field into branching mesas: organic outlines, flat tops,
    hard cliff edges, and a second tier nested inside the first. Nothing about
    that construction produces a way up, so CarveRamps finds every stranded
    region and cuts a constant-gradient corridor down to reachable ground,
    repeating until the whole map is connected.

    No river - the barriers here are the cliffs themselves.
#>
[CmdletBinding()]
param(
    [string]$MapsRoot = 'F:\SteamLibrary\steamapps\common\Sanctuary Shattered Sun Demo\engine\Sanctuary_Data\Maps',
    [string]$Folder   = 'Broken_Mesa',
    [string]$MapName  = 'Broken Mesa',
    [ValidateSet('.santp', '.sanprop')]
    [string]$PropExtension = '.santp',
    [int]$Size = 512,
    [int]$Seed = 20250822,
    [string]$DebugOut,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
. (Join-Path $here 'src' 'Import-MapGen.ps1')
. (Join-Path $here 'src' 'Biomes.ps1')

