function T {
    param([double]$X, [double]$Y, [double]$Z)
    [ordered]@{
        position = @{ x = $X;  y = $Y;  z = $Z }
        rotation = @{ x = 0.0; y = 0.0; z = 0.0; w = 1.0 }
        scale    = @{ x = 1.0; y = 1.0; z = 1.0 }
    }
}

$spawnT = [ordered]@{}
