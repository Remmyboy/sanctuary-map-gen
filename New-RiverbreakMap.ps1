# Alloys in river-relative coordinates: (t along the diagonal, metres from the
# centreline). Positive perp is the top-left player's bank; the mirror set is
# generated by (1-t, -perp), which is exactly the 180-degree rotation.
#
# Bank room runs out near the corners: at t, the top edge caps perp at about
# (Size - 10 - Size*(1-t)) / 0.7071, so a large offset at low t lands off the
# map. These are all inside that.
$alloySideA = @(
    @(0.20, 50),  @(0.24, 88),  @(0.33, 58),  @(0.31, 118),
    @(0.15, 48),  @(0.40, 92),  @(0.46, 148), @(0.55, 62),
