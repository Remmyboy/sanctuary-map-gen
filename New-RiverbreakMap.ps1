                scale    = @{ x = [math]::Round($sc,4); y = [math]::Round($sc,4); z = [math]::Round($sc,4) }
            }
        }
    }
    Write-Host ("  {0}: {1} per bank -> {2} total" -f $(if($set.Rocks){'rocks'}else{'trees'}), $n, ($n*2))
