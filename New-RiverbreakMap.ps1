    @{ Army = 'ARMY_2'; X = [double][MapGen]::BaseX[1]; Z = [double][MapGen]::BaseZ[1] }
)

function Test-Ok {
    param([double]$X, [double]$Z, [double]$MaxSlope, [double]$MinRiver)
    if ($X -lt 10 -or $X -gt ($M - 10) -or $Z -lt 10 -or $Z -gt ($M - 10)) { return $false }
    if ([MapGen]::HeightAtWorld($X, $Z) -le ([MapGen]::WaterLevel + 1.0)) { return $false }
    if ([MapGen]::SlopeAtWorld($X, $Z) -gt $MaxSlope) { return $false }
    if ([math]::Abs([MapGen]::RiverDist($X, $Z)) -lt $MinRiver) { return $false }
    [MapGen]::IsReachable($reach, $X, $Z)
}

function Resolve-Spot {
    param([double]$X, [double]$Z, [double]$MaxSlope, [double]$MinRiver, [string]$Label)
    if (Test-Ok $X $Z $MaxSlope $MinRiver) { return ,@($X, $Z) }
    foreach ($rad in 5, 10, 15, 21, 28, 36, 45) {
        foreach ($deg in 0..23) {
            $a = $deg * 15 * [math]::PI / 180
            $nx = [math]::Round($X + $rad * [math]::Cos($a))
            $nz = [math]::Round($Z + $rad * [math]::Sin($a))
            if (Test-Ok $nx $nz $MaxSlope $MinRiver) {
                Write-Host ("  nudged {0}: ({1:N0},{2:N0}) -> ({3},{4})  [{5} m]" -f $Label, $X, $Z, $nx, $nz, $rad)
                return ,@([double]$nx, [double]$nz)
            }
        }
    }
    Write-Warning "could not place $Label"
    return ,@($X, $Z)
}

Write-Host 'Placing markers...'
$resolvedA = @()
$i = 0
foreach ($rp in $alloySideA) {
    $i++
    $t = [float]$rp[0]
    $perp = [float]$rp[1]
    $wx = 0.0; $wz = 0.0
    [MapGen]::RiverToWorld($t, $perp, [ref]$wx, [ref]$wz)
    $resolvedA += ,(Resolve-Spot ([double]$wx) ([double]$wz) 12.0 34.0 ("alloy A{0}" -f $i))
}

$alloyPts = @()
foreach ($p in $resolvedA) { $alloyPts += ,@([double]$p[0], [double]$p[1]) }
foreach ($p in $resolvedA) {
    $rx = $M - [double]$p[0]
    $rz = $M - [double]$p[1]
    $alloyPts += ,@($rx, $rz)
}

